"""Compute measured AGV=1 vs AGV=2 KPI averages and seed-paired differences."""

from __future__ import annotations

import argparse
import csv
import math
from collections import defaultdict
from pathlib import Path

METRICS = (
    "arrived_jobs", "completed_jobs", "throughput_per_hour", "mean_lead_time_seconds",
    "m01_busy_fraction", "m02_busy_fraction",
)


def _number(value: str, metric: str) -> float | None:
    if metric == "mean_lead_time_seconds" and value == "":
        return None
    result = float(value)
    if not math.isfinite(result) or result < 0:
        raise ValueError(f"{metric} must be finite and nonnegative")
    if metric.endswith("busy_fraction") and result > 1:
        raise ValueError("machine utilization exceeds 1")
    return result


def compare_csv(path: str | Path) -> str:
    with Path(path).open(encoding="utf-8-sig", newline="") as file:
        reader = csv.DictReader(file)
        required = {"scenario_id", "seed", "duration_seconds", "event_hash", *METRICS}
        if set(reader.fieldnames or ()) != required:
            raise ValueError("unexpected KPI CSV schema")
        records = list(reader)
    if not records:
        raise ValueError("KPI CSV is empty")
    grouped: dict[str, dict[int, dict[str, float | None]]] = defaultdict(dict)
    for row in records:
        scenario = row["scenario_id"]
        if scenario not in ("agv_1", "agv_2"):
            raise ValueError("unexpected scenario; expected agv_1/agv_2")
        seed = int(row["seed"])
        if seed < 0 or seed in grouped[scenario]:
            raise ValueError("duplicate/invalid seed")
        duration = float(row["duration_seconds"])
        if not math.isfinite(duration) or duration <= 0:
            raise ValueError("invalid duration")
        if len(row["event_hash"]) != 64 or any(c not in "0123456789abcdef" for c in row["event_hash"]):
            raise ValueError("invalid event_hash")
        metrics = {metric: _number(row[metric], metric) for metric in METRICS}
        if metrics["completed_jobs"] > metrics["arrived_jobs"]:
            raise ValueError("completed_jobs exceeds arrived_jobs")
        if abs(metrics["throughput_per_hour"] - metrics["completed_jobs"] * 3600 / duration) > 1e-8:
            raise ValueError("throughput inconsistent with completed_jobs/duration")
        grouped[scenario][seed] = {**metrics, "_duration": duration}
    seeds_one = set(grouped["agv_1"])
    seeds_two = set(grouped["agv_2"])
    if seeds_one != seeds_two or len(seeds_one) < 3:
        raise ValueError("at least three matched seeds per scenario are required")
    for seed in seeds_one:
        if grouped["agv_1"][seed]["_duration"] != grouped["agv_2"][seed]["_duration"]:
            raise ValueError("paired runs must use the same duration")
        if grouped["agv_1"][seed]["arrived_jobs"] != grouped["agv_2"][seed]["arrived_jobs"]:
            raise ValueError("paired runs must use the same number of arrivals")

    def mean(values: list[float | None]) -> float | None:
        valid = [value for value in values if value is not None]
        return sum(valid) / len(valid) if valid else None

    def format_number(value: float | None) -> str:
        return "N/A" if value is None else f"{value:.6f}"

    result = [
        "# FactoryTwin AGV A/B comparison (simulated, measured CSV)", "",
        "Input: raw KPI rows generated by `factory_sim.runner`; seeded synthetic workload, not real factory measurements.", "",
        f"Paired seeds: {', '.join(map(str, sorted(seeds_one)))}", "",
        "| Metric | AGV=1 mean | AGV=2 mean | Δ (2 minus 1) |",
        "|---|---:|---:|---:|",
    ]
    for metric in METRICS:
        first = mean([grouped["agv_1"][seed][metric] for seed in sorted(seeds_one)])
        second = mean([grouped["agv_2"][seed][metric] for seed in sorted(seeds_one)])
        difference = second - first if first is not None and second is not None else None
        result.append(f"| {metric} | {format_number(first)} | {format_number(second)} | {format_number(difference)} |")
    result += [
        "", "Differences are descriptive, not confidence bounds or proof of a universal throughput gain.",
        "Machine faults, initial workload, arrivals, dispatch policy, and seed are identical within each paired run.",
        "The fixed-duration transport model has no empty AGV reposition, congestion, or collision physics.", "",
    ]
    return "\n".join(result)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="FactoryTwin paired KPI experiment report")
    parser.add_argument("--csv", required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args(argv)
    content = compare_csv(args.csv)
    from tempfile import NamedTemporaryFile
    import os
    target = Path(args.out)
    target.parent.mkdir(parents=True, exist_ok=True)
    temp_name = None
    try:
        with NamedTemporaryFile(mode="w", encoding="utf-8", dir=target.parent, delete=False) as temp:
            temp_name = temp.name
            temp.write(content)
            temp.flush()
            os.fsync(temp.fileno())
        os.replace(temp_name, target)
    finally:
        if temp_name is not None and os.path.exists(temp_name):
            os.unlink(temp_name)
    print(f"PASS compare {args.csv} -> {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
